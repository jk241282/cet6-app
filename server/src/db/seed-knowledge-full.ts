// 找出词根成分
function findRootComponents(word:string):string{
  const w=word.toLowerCase();
  const found:string[]=[];
  // Check prefixes
  for(const[p,m]of Object.entries(prefixes)){
    if(w.startsWith(p)&&w.length>p.length+2){found.push(`${p}(${m})`);break;}
  }
  // Check roots
  for(const[r,m]of Object.entries(roots)){
    if(w.includes(r)&&r.length>=3){found.push(`${r}(${m})`);break;}
  }
  // Check suffixes
  for(const[s,m]of Object.entries(suffixes)){
    if(w.endsWith(s)&&w.length>s.length+2){found.push(`-${s}(${m})`);break;}
  }
  return found.length>0?found.join(' + '):'';
}

// 生成记忆技巧
function makeMemoryTip(word:string,meaning:string):string|null{
  const comps=findRootComponents(word);
  if(!comps)return null;
  const firstChar=meaning.charAt(0);
  return `${comps} → ${meaning}`;
}

